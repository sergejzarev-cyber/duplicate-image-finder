const DICTS: Record<Lang, Dict> = { ru, en, de };

/** порядок падежей в массивах: ru — one/few/many, en/de — one/other */
const PLURAL_INDEX: Record<Lang, Record<string, number>> = {
  ru: { one: 0, few: 1, many: 2, two: 1, other: 2 },
  en: { one: 0, other: 1 },
  de: { one: 0, other: 1 },
};

export const LANG_LABELS: Record<Lang, string> = { ru: "RU", de: "DE", en: "EN" };
export const LANG_ORDER: Lang[] = ["ru", "de", "en"];

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Vars) => string;
  /** плюрализованная форма с подстановкой {n} */
  tp: (key: string, n: number, vars?: Vars) => string;
}

const I18nContext = createContext<I18n | null>(null);

function interpolate(s: string, vars?: Vars): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k: string) =>
    vars[k] !== undefined ? String(vars[k]) : `{${k}}`
  );
}

function isLang(v: unknown): v is Lang {
  return v === "ru" || v === "de" || v === "en";
}

/**
 * Стартовый язык:
 * 1. сохранённый выбор пользователя (localStorage) — высший приоритет;
 * 2. язык браузера (navigator.languages: "de-CH" → "de" и т.п.);
 * 3. fallback — немецкий (язык проекта по умолчанию).
 *
 * Уточнение: Windows напрямую не участвует — сайт видит только язык
 * браузера. Обычно он совпадает с языком ОС, но в Chrome его можно
 * сменить независимо: Настройки → Языки.
 */
function detectInitialLang(): Lang {
  try {
    const saved = localStorage.getItem("dupsweep.lang");
    if (isLang(saved)) return saved;
  } catch {
    /* приватный режим и т.п. — идём дальше */
  }
  try {
    const prefs: readonly string[] =
      navigator.languages && navigator.languages.length > 0
        ? navigator.languages
        : [navigator.language];
    for (const tag of prefs) {
      const base = tag.split("-")[0]?.toLowerCase();
      if (isLang(base)) return base;
    }
  } catch {
    /* ignore */
  }
  return "de";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectInitialLang);

  // <html lang> должен соответствовать с первого рендера (a11y, скринридеры)
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<I18n>(() => {
    const dict = DICTS[lang];
    const rules = new Intl.PluralRules(LOCALES[lang]);
    const t = (key: string, vars?: Vars): string => {
      const v = dict[key];
      if (typeof v === "string") return interpolate(v, vars);
      return key;
    };
    const tp = (key: string, n: number, vars?: Vars): string => {
      const v = dict[key];
      const forms = Array.isArray(v) ? v : [key];
      const cat = rules.select(n);
      const idx = PLURAL_INDEX[lang][cat] ?? forms.length - 1;
      const form = forms[Math.min(idx, forms.length - 1)] ?? forms[0] ?? key;
      return interpolate(form, { n, ...vars });
    };
    return {
      lang,
      setLang: (l: Lang) => {
        setLangState(l);
        try {
          localStorage.setItem("dupsweep.lang", l);
        } catch {
          /* ignore */
        }
        document.documentElement.lang = l;
      },
      t,
      tp,
    };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside provider");
  return ctx;
}
